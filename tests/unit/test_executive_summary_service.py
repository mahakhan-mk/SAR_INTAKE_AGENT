async def test_stored_risk_level_is_never_changed(db_session, seeded_assessment, executive_summary_prompt_path):
    await seed_completed_analysis(db_session, seeded_assessment)
    llm_client = SequencedSummaryClient(["Summary text."])
    service = build_executive_summary_service(executive_summary_prompt_path, llm_client)

    before = await AnalysisRepository().get_latest_completed_snapshot(db_session, seeded_assessment["assessment_id"])
    response = await service.generate(db_session, seeded_assessment["assessment_id"])
    after = await AnalysisRepository().get_latest_completed_snapshot(db_session, seeded_assessment["assessment_id"])

    assert response.executiveSummary.status == ExecutiveSummaryStatus.GENERATED
    assert before is not None and after is not None
    assert before.overall_risk_level == after.overall_risk_level == RiskLevel.CRITICAL


